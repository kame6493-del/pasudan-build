/** その敵を倒した数(模擬試験のボスは、模擬試験を終えた数) */
export const metCount = (d: AppData, e: Enemy) => (d.foes?.[e.key] ?? 0) || (e.key === 'boss_celes' ? d.exams.length : 0);

/** 図鑑に載った数 / 全部 */
export function bestiaryCount(d: AppData) {
  const all = bestiary().flatMap((g) => g.foes);
  return { got: all.filter((e) => metCount(d, e) > 0).length, all: all.length };
}

